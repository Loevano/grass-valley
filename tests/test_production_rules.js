const assert=require('node:assert/strict'),client=require('./client_harness');
const app=client();
app.run(`
 const town={name:'Town',wood:65,food:40,coins:20,level:5,goods:{},player:{x:5,y:7},
   buildings:[{kind:'hall',x:5,y:5}],villagers:[],map_resources:[]};
 const other={...town,name:'Other',rules:{production_caps:{wood:999}}};
 world={world_id:'test',towns:{own:town,friend:other},progression:{buildings:{},upgrades:{},job_requirements:{},crops:{wheat:1},edible:{fish:1},recipes:{sawpit:[{wood:2},'planks',1]}}};
 identity={town_id:'own'};viewed='friend';draw=()=>{};
 const commands=[];act=data=>commands.push(data);
 $('resources-button').onclick();
`);
const field=key=>app.run(`renderResourceList.rows.get('${key}').inputs.cap`);
const command=()=>JSON.parse(app.run('JSON.stringify(commands.pop())'));
assert(app.run("panel==='resources'&&$('resources-panel').open"),'Resources opens from toolbar');
assert.equal(field('planks').value,'');assert.equal(field('wood').placeholder,'Unlimited');
assert(!field('wood').disabled,'Caps do not require a market');
for(const key of ['food','coins','stone'])assert(!field(key),`${key} is not a production target`);
field('wood').value='0';field('wood').onchange();
assert.deepEqual(command(),{action:'configure_rule',resource:'wood',cap:0});
field('planks').value='100.5';field('planks').onchange();
assert.deepEqual(command(),{action:'configure_rule',resource:'planks',cap:100.5});
app.run('document.activeElement=renderResourceList.rows.get("planks").inputs.cap;render()');
assert.equal(field('planks').value,'100.5','Polling preserves focused edits');
app.run('town.rules={production_caps:{wood:0,planks:100.5}};document.activeElement=null;render()');
assert.equal(field('wood').value,'0');assert.equal(field('planks').value,'100.5');
field('wood').value='';field('wood').onchange();assert.equal(command().cap,null,'Blank removes the cap');
field('wood').reportValidity=()=>false;field('wood').value='-1';field('wood').onchange();
assert.equal(app.run('commands.length'),0,'Invalid numbers are not submitted');
field('wood').reportValidity=()=>true;
assert.equal(app.run('other.rules.production_caps.wood'),999,'Visiting another town leaves its caps untouched');
const stale=field('wood');
app.run('identity={town_id:"friend"};render()');stale.onchange();
assert.equal(app.run('commands.length'),0,'Old controls cannot change a different town');
const staleWorld=field('wood');app.run('world.world_id="another"');staleWorld.onchange();
assert.equal(app.run('commands.length'),0,'Old controls cannot change a different world');
app.run('identity=null;render()');
assert(app.run("$('resources-button').disabled&&!$('resources-panel').open"),'Unjoined visitors cannot edit caps');
console.log('Production caps in Resources passed');
