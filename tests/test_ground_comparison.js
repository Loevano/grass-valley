// Run with: node tests/test_ground_comparison.js
const fs=require('fs'),assert=require('assert');
const source=fs.readFileSync('web/app.js','utf8');
const matches=new Function(source.slice(source.indexOf('function groundMatchesCache('),source.indexOf('function drawGround('))+'return groundMatchesCache;')();
const landscape={map_size:120,terrain:Array(120).fill('g'.repeat(120)),terrain_seed:1};
const water=new Set(['30,30']),forest=new Set(['31,31']);
const cache={landscape,water,forest},bounds={minX:25,maxX:35,minY:25,maxY:35};
const snapshot=()=>JSON.parse(JSON.stringify(landscape));
assert(matches(snapshot(),new Set(water),bounds,new Set(forest),cache),'Equivalent snapshots preserve terrain');
let next=snapshot();next.terrain[24]='b'.repeat(120);
assert(!matches(next,water,bounds,forest,cache),'Neighboring terrain affects map edges');
next=snapshot();next.terrain[23]='b'.repeat(120);
assert(matches(next,water,bounds,forest,cache),'Changes outside the padded bounds preserve terrain');
assert(!matches(landscape,new Set(),bounds,forest,cache),'Removed water invalidates ground');
assert(!matches(landscape,water,bounds,null,cache),'Removed canopy invalidates ground');
assert(matches(landscape,new Set([...water,'100,100']),bounds,new Set([...forest,'100,100']),cache),'Distant water and trees preserve ground');
assert(!matches({...landscape,terrain_seed:2},water,bounds,forest,cache),'Water ripple seed invalidates ground');
assert(!matches({...landscape,map_size:121},water,bounds,forest,cache),'Map size invalidates ground');
const empty={map_size:120,terrain_seed:1};
assert(matches(empty,new Set(),bounds,null,{landscape,water:new Set(),forest:null}),'Legacy missing terrain defaults to grass');
assert(!matches({...empty,chunked:1},new Set(),bounds,null,{landscape,water:new Set(),forest:null}),'Unloaded chunked terrain stays distinct from grass');
let probes=0;
const counted={has(key){probes++;return water.has(key);}};
assert(matches(snapshot(),counted,bounds,forest,{...cache,water:counted}));
assert.equal(probes,0,'Unchanged water identities skip per-tile membership checks');
next=snapshot();next.terrain[24]='b'.repeat(120);
assert(!matches(next,counted,bounds,forest,cache));
assert.equal(probes,0,'Changed ground exits before scanning water or the remaining tiles');
console.log('Ground comparison checks passed');
