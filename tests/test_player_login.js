const assert=require('node:assert/strict');
const createClient=require('./client_harness');
const storage=new Map();
const localStorage={getItem:key=>storage.get(key) || null,setItem:(key,value)=>storage.set(key,value)};
const client=createClient({localStorage});
(async()=>{
  client.run(`world={world_id:'saved',towns:{town:{name:'Old village'}}}; identities.saved={token:'old',town_id:'town'}; render();`);
  assert.equal(client.elements.get('login-dialog').open,true);
  client.run(`$('player-name').value='Rowan';$('player-pin').value='4826';$('town-name-field').hidden=true;
    let sent;
    request=async(path,data,options)=>{sent={path,data,options};return {token:'old',town_id:'town'};};
    refresh=async()=>{};`);
  await client.run(`$('join-form').onsubmit({preventDefault(){}})`);
  assert.equal(client.run('identity.town_id'),'town');
  assert.equal(client.run('sent.path'),'/api/login');
  assert.equal(client.run('sent.options.headers.Authorization'),'old');
  assert.equal(client.run("$('player-pin').value"),'');
  assert.equal(client.elements.get('login-dialog').open,false);
  const remembered=JSON.parse(storage.get('lantern-identities'));
  assert.deepEqual(remembered.saved,{token:'old',town_id:'town'});
  assert.equal(storage.get('lantern-identities').includes('4826'),false);
  const reopened=createClient({localStorage});
  reopened.run(`refreshing=null;
    const town={name:'Old village',map_size:12,buildings:[],villagers:[],map_resources:[],level:1,wood:0,food:0,coins:0};
    let snapshot={world_id:'saved',towns:{town}};
    request=async path=>path==='/api/worlds'?{worlds:[],can_manage:false}:snapshot;`);
  await reopened.run('refresh()');
  assert.equal(reopened.run('identity.token'),'old');
  assert.equal(reopened.run('viewed'),'town');
  assert.equal(reopened.elements.get('login-dialog').open,false);
  reopened.run(`snapshot={world_id:'other',towns:{town:{...town,name:'Other village'}}};`);
  await reopened.run('refresh()');
  assert.equal(reopened.run('identity'),null);
  assert.equal(reopened.elements.get('login-dialog').open,true);
  reopened.run(`snapshot={world_id:'saved',towns:{town}};`);
  await reopened.run('refresh()');
  assert.equal(reopened.run('identity.token'),'old');
  assert.equal(reopened.elements.get('login-dialog').open,false);
  reopened.run(`snapshot={world_id:'saved',towns:{}};`);
  await reopened.run('refresh()');
  assert.equal(reopened.run('identity'),null);
  assert.equal(reopened.elements.get('login-dialog').open,true);
  const unavailable=createClient({localStorage:{getItem(){throw Error('Unavailable');},setItem(){throw Error('Unavailable');}}});
  assert.equal(unavailable.run('Object.keys(identities).length'),0);
  client.run(`request=async()=>({needs_town:true});$('town-name-field').hidden=true;`);
  await client.run(`$('join-form').onsubmit({preventDefault(){}})`);
  assert.equal(client.elements.get('town-name-field').hidden,false);
  client.run(`request=async()=>{throw Error('Incorrect player name or PIN.');};`);
  await client.run(`$('join-form').onsubmit({preventDefault(){}})`);
  assert.equal(client.elements.get('login-error').textContent,'Incorrect player name or PIN.');
  console.log('Player login controls passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
